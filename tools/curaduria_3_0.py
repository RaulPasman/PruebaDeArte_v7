def fetch(url):
    import urllib.parse
    url = urllib.parse.quote(url, safe=":/?=&%()!,")  # direcciones con acentos (ej. "Calderón")
    for intento in range(3):
        try:
            return urllib.request.urlopen(urllib.request.Request(url, headers={**UA, "Referer": url}), timeout=120).read()
        except Exception as e:
            print(f"   reintento ({e})")
    raise SystemExit(f"No se pudo bajar {url}")


def trim_background(im, tol=14):
    """Recorta el fondo liso (gris claro o blanco) de las fotos de producto, con un margen chico."""
    from PIL import ImageChops
    bg = Image.new("RGB", im.size, im.getpixel((2, 2)))
    box = ImageChops.difference(im, bg).convert("L").point(lambda v: 255 if v > tol else 0).getbbox()
    if not box:
        return im
    pad = int(0.02 * max(im.size))
    box = (max(0, box[0] - pad), max(0, box[1] - pad), min(im.width, box[2] + pad), min(im.height, box[3] + pad))
    return im.crop(box)


def web_jpg(src: Path, dest: Path, trim=False):
    im = Image.open(src)
    im = im.convert("RGB")
    if trim:
        im = trim_background(im)
    im.thumbnail((1600, 1600), Image.LANCZOS)
    im.save(dest, "JPEG", quality=86, optimize=True, progressive=True)
    return im.size


